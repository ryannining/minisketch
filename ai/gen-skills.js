'use strict';
// gen-skills.js — Compile ai/skills/*.md into ai/skills.js.
//
// The skill RECIPES are authored as Markdown (frontmatter: name, trigger,
// description) because that reads well and diffs cleanly. The frontend can't
// list a directory over HTTP, so this compiles them into one plain script that
// prompt.js reads off window.MiniSketchAISkills.
//
// Run after adding/editing a skill:  node ai/gen-skills.js
// (The output is committed, so the app never needs Node at runtime.)

const fs = require('fs');
const path = require('path');

const dir = __dirname;
const skillsDir = path.join(dir, 'skills');
const outFile = path.join(dir, 'skills.js');

const files = fs.readdirSync(skillsDir).filter(f => f.endsWith('.md')).sort();
const skills = [];

for (const f of files) {
  const raw = fs.readFileSync(path.join(skillsDir, f), 'utf8');
  // frontmatter: ---\n...\n---\n<body>
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) {
    console.warn('gen-skills: skip (no frontmatter): ' + f);
    continue;
  }
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^(\w+):\s*(.+)$/);
    if (kv) meta[kv[1]] = kv[2].trim();
  }
  skills.push({
    name: meta.name || f.replace(/\.md$/, ''),
    trigger: meta.trigger || '',
    description: meta.description || '',
    body: m[2].trim()
  });
}

const banner = '// GENERATED by ai/gen-skills.js — do not hand-edit.\n' +
  '// Source of truth: ai/skills/*.md. Edit there, then run: node ai/gen-skills.js\n' +
  '// Read by ai/prompt.js (window.MiniSketchAISkills) to inject active recipes.\n';
const body = 'window.MiniSketchAISkills = ' + JSON.stringify(skills, null, 2) + ';\n';

fs.writeFileSync(outFile, banner + body, 'utf8');
console.log('gen-skills: wrote ' + outFile + ' (' + skills.length +
  ' skill' + (skills.length === 1 ? '' : 's') + ': ' + skills.map(s => s.name).join(', ') + ')');
